        button.classList.add('js-tab-active');

        // すべてのタブコンテンツを非表示
        tabContents3.forEach(content => {
          content.style.display = "none";
        });

        // クリックされたタブに対応するコンテンツを表示
        const tabId3 = button.getAttribute('data-tab3');
        const targetTab3 = document.getElementById(tabId3);
